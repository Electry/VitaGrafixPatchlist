# Unpacks the fixed .fpo shaders (8-byte header + zlib GXP) into shaders.h
import glob, os, struct, sys, zlib
here = os.path.dirname(os.path.abspath(__file__))
out = ["/* generated by gen_shaders.py from the shaders folder */", "#include <stdint.h>"]
names = []
for path in sorted(glob.glob(os.path.join(here, "shaders", "*.fpo"))):
    raw = open(path, "rb").read()
    clen, ulen = struct.unpack_from(">HH", raw, 4)
    gxp = zlib.decompress(raw[8:8 + clen])
    size = struct.unpack_from("<I", gxp, 8)[0]  # program size; the blob is padded to 4 bytes
    assert len(gxp) == ulen and gxp[:4] == b"GXP\0" and size <= ulen
    name = os.path.basename(path)[:-4]
    names.append((name, size))
    body = ",".join(str(b) for b in gxp)
    out.append(f"static const uint8_t {name}[{ulen}] __attribute__((aligned(16))) = {{{body}}};")
out.append("static const struct { const char *name; const uint8_t *gxp; uint32_t size; } fixes[] = {")
out += [f'  {{"{n}", {n}, {s}}},' for n, s in names]
out.append("};")
open(os.path.join(here, "shaders.h"), "w").write("\n".join(out) + "\n")
print(names)
